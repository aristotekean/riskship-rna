  "status_1" text,
  "date_status_2" timestamp,
  "status_2" text,
  "date_status_3" timestamp,
  "status_3" text,
  "date_status_4" timestamp,
  "status_4" text,
  "date_status_5" timestamp,
  "status_5" text,
  "date_status_6" timestamp,
  "status_6" text,
  "date_status_7" timestamp,
  "status_7" text,
  "date_status_8" timestamp,
  "status_8" text,
  "date_status_9" timestamp,
  "status_9" text,
  "date_status_10" timestamp,
  "status_10" text,
  "is_lost" bigint,
  "batch_num" bigint,
  "source_file" text
);
CREATE INDEX IF NOT EXISTS shipments_shipment_id_idx ON shipments ("SHIPMENT_ID");
CREATE INDEX IF NOT EXISTS shipments_created_at_idx ON shipments (created_at);
