-- Postgres (Neon) mirror of dataset.parquet, read by the Hermes profile `riskship`
-- (cron riesgo-envio-neon, script scripts/neon_fetch_shipments.sh).
-- Generated from the parquet schema: same 58 columns, same names (quoted,
-- case preserved), one row per shipment item exactly as in the dataset. Two
-- bookkeeping columns are added: id (the cron's watermark) and created_at.
-- Created and loaded by load_neon.py at the project root.
