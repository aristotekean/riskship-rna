  id          bigserial PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  "SHIPMENT_ID" text,
  "SHP_SHIPMENT_ID" text,
  "PAIS" text,
  "PICKING_TYPE" text,
  "FUE_AVION" boolean,
  "LG_FACILITY_NAME" text,
  "SHP_LG_FACILITY_ID" text,
  "LG_REGION" text,
  "DOM_DOMAIN_ID" text,
  "ITE_ITEM_ID" text,
  "ITE_ITEM_DESC" text,
  "ORD_CATEGORY_ID_L1" text,
  "ORD_CATEGORY_NAME_L1" text,
  "BRAND_NAME" text,
  "PESO_TOTAL_KG" bigint,
  "DIM_MAX_CM" bigint,
  "VALOR_TOTAL_USD" double precision,
  "CANTIDAD_ITEMS" bigint,
  "CANT_BULTOS" text,
  "ES_BULKY" boolean,
  "TIPO_BULKY" text,
  "RATIO_SVC_MES_ANTERIOR" double precision,
  "TOTALGMV" bigint,
  "BPP_CASHOUT_USD" double precision,
  "DATEPARAMETER" date,
  "CLASSIFICATION_LM" text,
  "SUBSTATUS_CLASIFICATION" text,
  "DATE_BPP" date,
  "CAUSA_BPP" text,
  "L1_CAUSA_BPP" text,
  "L2_CAUSA_BPP" text,
